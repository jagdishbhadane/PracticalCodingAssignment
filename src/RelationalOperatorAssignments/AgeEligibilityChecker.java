package RelationalOperatorAssignments;

public class AgeEligibilityChecker {

    public static void main(String[] args) {

        int age = 20; // input

        if (age >= 18) { // condition
            System.out.println("Eligible: Age is greater than or equal to 18");
        } else {
            System.out.println("Not Eligible: Age is less than 18");
        }
        
    }
}