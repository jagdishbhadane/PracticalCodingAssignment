package RelationalOperatorAssignments;

public class ProductPriceComparison {

	public static void main(String[] args) {
		 int price1 = 500;  // input 
	     int price2 = 500;

	        if (price1 == price2) { // condition 1
	            System.out.println("Both prices are equal");
	        } else {
	            System.out.println("Prices are not equal");
	        }

	        if (price1 >= price2) {  // condition 2
	            System.out.println("Price1 is greater than or equal to Price2");
	        } else {
	            System.out.println("Price1 is less than Price2");
	        }

	}

}
