package Literals;
public class Literals {
    public static void main(String[] args)
    {
         int age=23;
         String name="Jagdish";
         char ch='a';
         float f=24.56f;
         double d=23.34;
         boolean ispassed=true;

         System.out.println("Intenger Literals :"+age);
         System.out.println("String Literals :"+name);
         System.out.println("Character Literals:"+ch);
         System.out.println("Floating Point Literals :"+f);
         System.out.println("Double Literals :"+d);
         System.out.println("boolean Literals :"+ispassed);
    }
}
