package BODMASArithmeticOperatorsAssignments;

public class BracketsCalculator {

	public static void main(String[] args) {
		
		int a=10; 
		int b=5;
		
		System.out.println("===== Brackets Calculator =====");
		System.out.println();
		System.out.println("(a + b) * 2 = " + ((a + b) * 2));
		System.out.println("(a - b) * 3 = " + ((a - b) * 3));
		System.out.println("(a + b) / 3 = " + ((a + b) / 3));
		System.out.println("(a * b) + 10 = " + ((a * b) + 10));
		System.out.println("(a + b) * (a - b) = " + ((a + b) * (a - b)));

	}

}
